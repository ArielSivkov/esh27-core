#!/usr/bin/env python3
"""G050 -- reproducible SAT pipeline for small Schur / van der Waerden numbers.

  1. lower bounds: solve the SAT instance at n = value, decode a colouring,
     re-check it with an independent exact checker (encode.check_*).
  2. upper bounds: the instance at n = value + 1 must be UNSAT.  CaDiCaL
     writes a DRAT proof and an LRAT proof; drat-trim checks the DRAT proof,
     lrat-check checks the LRAT proof (both against the CNF we wrote).
  3. writes results.json, witnesses.json and the Lean witness file
     ../../lean/EshLab/Targets/G050/Witnesses.lean (generated).

Usage:  ./setup_tools.sh && python3 run_all.py [--sym] [--skip-big]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import subprocess
import sys
import time
from pathlib import Path

from pysat.solvers import Cadical153

import encode

HERE = Path(__file__).resolve().parent
TOOLS = HERE / "tools"
CADICAL = os.environ.get("CADICAL", str(TOOLS / "cadical/build/cadical"))
DRAT_TRIM = os.environ.get("DRAT_TRIM", str(TOOLS / "drat-trim/drat-trim"))
LRAT_CHECK = os.environ.get("LRAT_CHECK", str(TOOLS / "drat-trim/lrat-check"))
PROOFS = HERE / "proofs"
LEAN_WIT = HERE.parent.parent / "lean/EshLab/Targets/G050/Witnesses.lean"

# (family, k colours, L (AP length, vdW only), known value)
# Schur value S(k) = largest good n.  vdW value W(k,L) = least n with no good colouring.
INSTANCES = [
    ("schur", 1, None, 1),
    ("schur", 2, None, 4),
    ("schur", 3, None, 13),
    ("schur", 4, None, 44),
    ("vdw", 2, 3, 9),
    ("vdw", 3, 3, 27),
    ("vdw", 2, 4, 35),
]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def cnf(fam, k, L, n, sym):
    return encode.schur_cnf(k, n, sym) if fam == "schur" else encode.vdw_cnf(k, L, n, sym)


def name(fam, k, L, n):
    return f"schur_k{k}_n{n}" if fam == "schur" else f"vdw_k{k}_L{L}_n{n}"


def solve_sat(fam, k, L, n, sym):
    cls = cnf(fam, k, L, n, sym)
    t = time.perf_counter()
    with Cadical153(bootstrap_with=cls) as s:
        sat = s.solve()
        model = s.get_model() if sat else None
    dt = time.perf_counter() - t
    if not sat:
        return None, dt
    col = encode.decode(model, k, n)
    ok = encode.check_schur(col, k) if fam == "schur" else encode.check_vdw(col, k, L)
    assert ok, "decoded colouring failed the independent check"
    return col, dt


def prove_unsat(fam, k, L, n, sym):
    PROOFS.mkdir(exist_ok=True)
    base = PROOFS / name(fam, k, L, n)
    cnf_path = base.with_suffix(".cnf")
    cls = cnf(fam, k, L, n, sym)
    encode.write_dimacs(cls, n * k, str(cnf_path),
                        comment=f"G050 {fam} k={k} L={L} n={n} sym={sym}\n"
                                f"var(i,j)=(i-1)*k+j+1 : integer i has colour j")
    out = {"cnf": str(cnf_path.relative_to(HERE)), "cnf_sha256": sha256(cnf_path),
           "vars": n * k, "clauses": len(cls), "sym": sym}
    for fmt in ("drat", "lrat"):
        proof = base.with_suffix("." + fmt)
        args = [CADICAL, "-q", "--binary=false", str(cnf_path), str(proof)]
        if fmt == "lrat":
            args.insert(1, "--lrat=true")
        t = time.perf_counter()
        r = subprocess.run(args, capture_output=True, text=True)
        out[f"solve_{fmt}_s"] = round(time.perf_counter() - t, 3)
        assert r.returncode == 20, f"expected UNSAT (20), got {r.returncode}: {r.stdout[-500:]}"
        out[f"{fmt}_bytes"] = proof.stat().st_size
        out[f"{fmt}_sha256"] = sha256(proof)
        t = time.perf_counter()
        if fmt == "drat":
            c = subprocess.run([DRAT_TRIM, str(cnf_path), str(proof), "-t", "20000"],
                               capture_output=True, text=True)
            verified = "s VERIFIED" in c.stdout
        else:
            c = subprocess.run([LRAT_CHECK, str(cnf_path), str(proof)],
                               capture_output=True, text=True)
            # lrat-check prints "c VERIFIED" (drat-trim prints "s VERIFIED")
            verified = any(l.strip() in ("c VERIFIED", "s VERIFIED") for l in c.stdout.splitlines())
        out[f"check_{fmt}_s"] = round(time.perf_counter() - t, 3)
        out[f"{fmt}_verified"] = verified
        out[f"{fmt}_checker_verdict"] = [l for l in c.stdout.splitlines() if "VERIFIED" in l]
    return out


def lean_witnesses(wits):
    lines = [
        "/-",
        "EshLab.Targets.G050.Witnesses -- GENERATED by lab/experiments/G050/run_all.py.",
        "Do not edit by hand.  Each list `l` is a colouring of 1..length l:",
        "the colour of the integer i is  l[i-1]  (see `ofList` in Defs.lean).",
        "Every witness was found by CaDiCaL and re-checked by an exact Python checker;",
        "the Lean kernel re-checks it again (Lower.lean).",
        "-/",
        "namespace EshLab.G050.Witnesses",
        "",
    ]
    for key, col in wits.items():
        lines.append(f"/-- {key}: {len(col)} integers. -/")
        lines.append(f"def {key} : List Nat :=")
        lines.append("  [" + ", ".join(map(str, col)) + "]")
        lines.append("")
    lines.append("end EshLab.G050.Witnesses")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sym", action="store_true", help="add colour-1 symmetry-breaking unit")
    ap.add_argument("--skip-big", action="store_true", help="skip UNSAT proofs for S(4), W(3,3), W(2,4)")
    a = ap.parse_args()

    results = {"python": sys.version.split()[0], "platform": platform.platform(),
               "cadical": subprocess.run([CADICAL, "--version"], capture_output=True, text=True).stdout.strip(),
               "instances": []}
    wits = {}
    for fam, k, L, val in INSTANCES:
        lo_n = val if fam == "schur" else val - 1   # largest good n
        rec = {"family": fam, "k": k, "L": L, "known_value": val, "good_n": lo_n}
        col, dt = solve_sat(fam, k, L, lo_n, False)
        rec["lower_sat_s"] = round(dt, 3)
        rec["lower_witness_found"] = col is not None
        if col is not None:
            key = (f"schur{k}_{lo_n}" if fam == "schur" else f"vdw{k}_{L}_{lo_n}")
            wits[key] = col
            rec["witness_key"] = key
        big = (fam, k, L) in {("schur", 4, None), ("vdw", 3, 3), ("vdw", 2, 4)}
        if a.skip_big and big:
            rec["upper"] = "skipped"
        else:
            rec["upper"] = prove_unsat(fam, k, L, lo_n + 1, a.sym)
        print(json.dumps(rec), flush=True)
        results["instances"].append(rec)

    (HERE / "witnesses.json").write_text(json.dumps(wits, indent=1) + "\n")
    (HERE / ("results_sym.json" if a.sym else "results.json")).write_text(json.dumps(results, indent=1) + "\n")
    LEAN_WIT.parent.mkdir(parents=True, exist_ok=True)
    LEAN_WIT.write_text(lean_witnesses(wits))


if __name__ == "__main__":
    main()
