#!/usr/bin/env python3
"""Embed a CaDiCaL LRAT proof (ASCII) into a Lean file as a `String` literal.

The certificate is untrusted data.  In Lean it is parsed by core Lean's LRAT parser and
checked by core Lean's LRAT checker (`Std.Tactic.BVDecide.LRAT.check`, proved sound as
`LRAT.check_sound`) against the CNF *generated in Lean* (`schurCNF` / `vdwCNF`), see
lean/EshLab/Targets/G050/LRAT.lean and UpperLRAT.lean.

Usage: python3 lrat_to_lean.py proofs/schur_k3_n14.lrat schur3_14 > ../../lean/EshLab/Targets/G050/Certs/Schur3.lean
"""

from __future__ import annotations

import hashlib
import json
import sys


def to_lean(text: str, name: str, src: str, sha: str) -> str:
    return (
        f"/- GENERATED by lab/experiments/G050/lrat_to_lean.py from {src}\n"
        f"   (CaDiCaL LRAT proof, sha256 {sha}).\n"
        f"   Untrusted data: parsed and checked by core Lean's LRAT checker. -/\n"
        f"namespace EshLab.G050.Certs\n\n"
        f"def {name} : String :=\n  {json.dumps(text)}\n\n"
        f"end EshLab.G050.Certs\n"
    )


if __name__ == "__main__":
    path, name = sys.argv[1], sys.argv[2]
    raw = open(path, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    sys.stdout.write(to_lean(raw.decode("ascii"), name, path, sha))
