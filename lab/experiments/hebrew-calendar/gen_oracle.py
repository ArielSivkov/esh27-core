"""Generate cross-check data for lab/lean/Hebrew from the reference oracle
lab/experiments/novelty/sanity/hebrew_period.py (Dershowitz-Reingold formulas).

Only the function definitions of the oracle are executed (its top-level
689472-year scan is skipped). Convention: the oracle's day number ny(y) is
shifted by +1 to our Lean day index (day 0 = Sunday of the BaHaRaD week,
Lean `weekday d = d % 7 + 1`, 1 = Sunday ... 7 = Shabbat).

Writes lab/lean/Hebrew/Hebrew/Oracle.lean and prints witness years.
"""
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
LAB = HERE.parent.parent
src = (LAB / "experiments/novelty/sanity/hebrew_period.py").read_text()
defs = src.split("\nN=689472")[0]          # function definitions only
ns: dict = {}
exec(compile(defs, "hebrew_period.py(defs)", "exec"), ns)
ny = ns["ny"]

YMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 10000
rh = [ny(y) + 1 for y in range(1, YMAX + 2)]          # years 1..YMAX+1

def keviyah(y):
    a, b = ny(y) + 1, ny(y + 1) + 1
    return (a % 7 + 1, b - a)

N = 689472
# witnesses for the 14 keviyot (first occurrence)
first = {}
for y in range(1, 3000):
    first.setdefault(keviyah(y), y)
print("keviyot first years:", sorted(first.items()))
# minimality witnesses: smallest y with keviyah(y + N/p) != keviyah(y)
for p in (2, 3, 7, 19):
    d = N // p
    y = 1
    while keviyah(y + d) == keviyah(y):
        y += 1
    print(f"p={p} d={d} y={y} k(y)={keviyah(y)} k(y+d)={keviyah(y + d)}")

out = LAB / "lean/Hebrew/Hebrew/Oracle.lean"
CH = 500   # a single 10001-element array literal overflows the elaborator; chunk it
chunks = [rh[i:i + CH] for i in range(0, len(rh), CH)]
lines = [
    "/-! AUTO-GENERATED by lab/experiments/hebrew-calendar/gen_oracle.py from the\n"
    "reference oracle lab/experiments/novelty/sanity/hebrew_period.py. Do not edit.\n"
    f"`oracleRH[i]` = day index of Rosh Hashana of year i+1, for years 1..{YMAX + 1}. -/\n"
    "namespace Hebrew"]
for j, c in enumerate(chunks):
    lines.append(f"def oracleRH{j} : Array Nat := #[{','.join(map(str, c))}]")
lines.append("def oracleRH : Array Nat := " + " ++ ".join(f"oracleRH{j}" for j in range(len(chunks))))
lines.append("end Hebrew\n")
out.write_text("\n".join(lines))
print("wrote", out, len(rh), "values in", len(chunks), "chunks")
