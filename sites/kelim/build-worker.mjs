// Builds worker.js: a tiny Worker that serves the files in ./public, embedded as strings.
// (No static-assets upload step needed; deployable with one script PUT.)
import fs from 'fs';
import path from 'path';
const PUB = new URL('./public/', import.meta.url).pathname;
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8', '.json': 'application/json; charset=utf-8' };
const files = {};
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) { walk(p); continue; }
    if (f === '_headers') continue;
    const rel = '/' + path.relative(PUB, p).split(path.sep).join('/');
    files[rel] = { t: TYPES[path.extname(f)] || 'application/octet-stream', b: fs.readFileSync(p, 'utf8') };
  }
})(PUB);
const csp = fs.readFileSync(path.join(PUB, '_headers'), 'utf8').match(/Content-Security-Policy: (.*)/)[1].trim();
const src = `// כֵּלִים · kelim.esh27.com — generated by build-worker.mjs from ./public. Do not edit by hand.
const FILES = ${JSON.stringify(files)};
const CSP = ${JSON.stringify(csp)};
const BASE = { 'Content-Security-Policy': CSP, 'X-Content-Type-Options': 'nosniff', 'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()', 'Cache-Control': 'public, max-age=300' };
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('method not allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
    let p = decodeURIComponent(url.pathname);
    if (!p.endsWith('/') && FILES[p + '/index.html']) return Response.redirect(url.origin + p + '/' + url.search, 301);
    if (p.endsWith('/')) p += 'index.html';
    const f = FILES[p];
    const h = { ...BASE };
    if (p === '/kelim.json') h['Access-Control-Allow-Origin'] = '*';
    if (!f) { const nf = FILES['/404.html']; return new Response(request.method === 'HEAD' ? null : nf.b, { status: 404, headers: { ...h, 'Content-Type': nf.t } }); }
    return new Response(request.method === 'HEAD' ? null : f.b, { status: 200, headers: { ...h, 'Content-Type': f.t } });
  }
};
`;
fs.writeFileSync(new URL('./worker.js', import.meta.url), src);
console.log('worker.js', src.length, 'bytes,', Object.keys(files).length, 'files:', Object.keys(files).join(' '));
